// Writes Paper Shaders' `liquidMetal` fragment shader into the library as a
// string, unmodified, so the published package has no runtime dependency on
// `@paper-design/shaders` (which is pinned in devDependencies for this).
//
//   node scripts/vendor-liquid-metal.mjs
//
// Run it again after changing the pinned version, and update NOTICE.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { liquidMetalFragmentShader } from '@paper-design/shaders';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const pkgPath = join(dirname(require.resolve('@paper-design/shaders')), '..', 'package.json');
const { version } = JSON.parse(readFileSync(pkgPath, 'utf8'));

const out = `/**
 * Paper Shaders' \`liquidMetal\` fragment shader, unmodified.
 *
 * Source: @paper-design/shaders@${version} (https://github.com/paper-design/shaders)
 * Copyright (c) Paper Design, Inc. Licensed under the Apache License,
 * Version 2.0. See NOTICE and LICENSES/Apache-2.0.txt at the package root.
 *
 * Generated by scripts/vendor-liquid-metal.mjs. Do not edit by hand.
 */
export const liquidMetalFragmentShader: string = ${JSON.stringify(liquidMetalFragmentShader)};
`;
writeFileSync(join(here, '..', 'src', 'metal-fx', 'engine', 'liquidMetal.frag.ts'), out);
console.log(`liquidMetal @ ${version}: ${liquidMetalFragmentShader.length} characters`);
